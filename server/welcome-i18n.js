export function resolveWelcomeLang(raw) {
  const code = String(raw || '')
    .trim()
    .slice(0, 2)
    .toLowerCase();
  return WELCOME_I18N[code] ? code : 'en';
}

export function welcomeCopy(lang) {
  return WELCOME_I18N[resolveWelcomeLang(lang)];
}
